let filterGrade = "all";
let filterTier = "all";
let filterSubject = "all";
let savedOnly = false;
let saved;
try {
  const storedRoutes = JSON.parse(localStorage.getItem("abirs-academy-saved") || "[]");
  saved = new Set(Array.isArray(storedRoutes) ? storedRoutes : []);
} catch {
  saved = new Set();
}
let toastTimer;

function safeText(value) {
  if (!value) return "";
  return String(value).replace(/[&<>'"]/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#039;", '"': "&quot;"
  })[character]);
}

function updateSavedUI() {
  document.querySelector("[data-saved-count]").textContent = saved.size;
  savedFilter.setAttribute("aria-pressed", String(savedOnly));
}

function showToast(message) {
  clearTimeout(toastTimer);
  toast.textContent = message;
  toast.classList.add("is-visible");
  toastTimer = setTimeout(() => toast.classList.remove("is-visible"), 1800);
}

function visibleResources() {
  const query = search.value.trim().toLowerCase();
  let items = libraryResources.filter((resource) => {
    const matchesGrade = filterGrade === "all" || resource.grade.toString() === filterGrade.replace("grade-", "");
    const matchesTier = filterTier === "all" || resource.tier === filterTier;
    const matchesSubject = filterSubject === "all" || resource.subject === filterSubject;
    const matchesSaved = !savedOnly || saved.has(resource.id);
    const searchable = `${resource.title} ${resource.description} ${resource.topic} ${resource.board}`.toLowerCase();
    
    return matchesGrade && matchesTier && matchesSubject && matchesSaved && searchable.includes(query);
  });
  
  if (sort.value === "az") items.sort((a, b) => a.title.localeCompare(b.title));
  // default to sorting by grade, then title
  else items.sort((a, b) => a.grade - b.grade || a.title.localeCompare(b.title));
  
  return items;
}

function render() {
  const items = visibleResources();
  resultCount.textContent = items.length;
  empty.hidden = items.length > 0;
  grid.hidden = items.length === 0;
  
  const hasActiveFilters = filterGrade !== "all" || filterTier !== "all" || filterSubject !== "all" || savedOnly || search.value;
  document.querySelector("[data-clear-filters]").hidden = !hasActiveFilters;
  
  grid.innerHTML = items.map((resource) => {
    const isSaved = saved.has(resource.id);
    const hasWorksheet = !!resource.worksheet_url;
    const hasSolution = !!resource.solution_url;
    
    return `
      <article class="library-item">
        <div class="library-item-top">
          <span class="library-item-type">Grade ${resource.grade} | ${safeText(resource.tier)}</span>
          <button class="save-button${isSaved ? " is-saved" : ""}" type="button" data-save="${resource.id}" aria-pressed="${isSaved}" aria-label="${isSaved ? "Remove" : "Save"} ${safeText(resource.title)}">${isSaved ? "★" : "☆"}</button>
        </div>
        <h3>${safeText(resource.title)}</h3>
        <p>${safeText(resource.description)}</p>
        <div class="item-meta"><span>${safeText(resource.subject)}</span><span>${safeText(resource.board)}</span></div>
        <div class="button-group" style="display: flex; gap: 0.5rem; margin-top: 1rem;">
          ${hasWorksheet ? `<a href="${resource.worksheet_url}" class="open-resource-btn button button-outline" data-url="${resource.worksheet_url}" data-target="worksheet">Worksheet</a>` : ''}
          ${hasSolution ? `<a href="${resource.solution_url}" class="open-resource-btn button button-outline" data-url="${resource.solution_url}" data-target="solution">Solution</a>` : ''}
        </div>
      </article>
    `;
  }).join("");

  grid.querySelectorAll("[data-save]").forEach((button) => {
    button.addEventListener("click", () => {
      const id = button.getAttribute("data-save");
      if (saved.has(id)) {
        saved.delete(id);
        button.setAttribute("aria-pressed", "false");
        button.classList.remove("is-saved");
        button.textContent = "☆";
        showToast("Removed from saved routes");
      } else {
        saved.add(id);
        button.setAttribute("aria-pressed", "true");
        button.classList.add("is-saved");
        button.textContent = "★";
        showToast("Saved to routes");
      }
      localStorage.setItem("abirs-academy-saved", JSON.stringify([...saved]));
      updateSavedUI();
      if (savedOnly) render();
    });
  });
  
  // Attach modal listeners after render
  attachModalListeners();
}

function updateActiveFilter(buttons, activeValue, dataAttr) {
  buttons.forEach((button) => {
    const val = button.getAttribute(dataAttr);
    button.classList.toggle("is-active", val === activeValue);
  });
}

